    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {
            // Ambil nilai dari komponen
            String nama = cbSparepart.getSelectedItem().toString();
            int qty = (Integer) sJumlah.getValue();
            
            int stokTersedia = Integer.parseInt(tfStok.getText());
            
            if (qty > stokTersedia) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Gagal! Stok " + nama + " tidak mencukupi.\nSisa stok saat ini hanya: " + stokTersedia,
                        "Stok Kurang",
                        javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            // Validasi: Cegah jika kasir belum milih barang atau jumlahnya 0
            if (nama.contains("Pilih") || qty == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Pilih barang dan pastikan jumlah lebih dari 0!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
                return; // Hentikan proses
            }
            
            // Ambil teks angka bertitik, lalu bersihkan titiknya sebelum dikonversi
            double harga = Double.parseDouble(tfHargaSatuan.getText().replace(".", "")); // Kolom harga satuan
            double subtotal = Double.parseDouble(tfSubtotal.getText().replace(".", "")); // Kolom subtotal

            // Potong stok di database sementara
            int indeksPilihan = cbSparepart.getSelectedIndex();
            
            // Ambil kode dari array statis
            String kodeBarang = kodeGlobal[indeksPilihan];
            
            // Bungkus ke dalam Array Object
            dataBaru = new Object[]{"", kodeBarang, nama, qty, (int) harga, (int) subtotal};
            
            stokGlobal[indeksPilihan] = stokGlobal[indeksPilihan] - qty;
            
            // Tutup pop-up
            this.dispose();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Terjadi kesalahan sistem", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahActionPerformed

