    private void cbSparepartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbSparepartActionPerformed
        // 1. PENGAMAN: Pastikan combobox sudah siap dan tidak kosong
        if (cbSparepart.getSelectedItem() == null) {
            return;
        }

        // Ambil urutan index yang dipilih
        int pilihan = cbSparepart.getSelectedIndex();
        double hargaSatuan = 0;
        String kategori = "-";
        String satuan = "-";
        int stokSisa = 0;

        // 2. KONDISI DEFAULT: Jika kasir memilih index 0 ("- Pilih Sparepart -")
        if (pilihan == 0) {
            tfHargaSatuan.setText("");
            tfStok.setText("");
            tfSatuan.setText("");
            lblKategori.setText("-"); // Kembalikan label kategori jadi strip
            return; // Hentikan eksekusi kode di bawahnya
        }

        // 3. LOGIKA HARGA & KATEGORI
        switch (pilihan) {
            case 1:
                hargaSatuan = 750000;
                kategori = "Penyimpanan / Storage";
                satuan = "pcs";
                break;
            case 2:
                hargaSatuan = 550000;
                kategori = "Memori / RAM";
                satuan = "pcs";
                break;
            case 3:
                hargaSatuan = 300000;
                kategori = "Memori / RAM";
                satuan = "pcs";
                break;
            case 4:
                hargaSatuan = 525000;
                kategori = "Penyimpanan / Storage";
                satuan = "pcs";
                break;
            // Tambahkan case selanjutnya di sini jika sparepart bertambah
            default:
                hargaSatuan = 0;
                kategori = "-";
                satuan = "-";
                break;
        }

        // 4. PENGAMAN ARRAY: Mengambil stok dari array global secara aman
        try {
            stokSisa = stokGlobal[pilihan];
        } catch (Exception e) {
            stokSisa = 0; // Mencegah error jika array stokGlobal belum diisi lengkap
        }

        // 5. TAMPILKAN KE UI
        // Update Label Kategori
        lblKategori.setText(kategori);

        // Buat desimal format lokal (Rupiah)
        java.text.DecimalFormat df = new java.text.DecimalFormat("#,###");
        java.text.DecimalFormatSymbols dfs = new java.text.DecimalFormatSymbols();
        dfs.setGroupingSeparator('.');
        df.setDecimalFormatSymbols(dfs);

        // Tampilkan harga ke tfHargaSatuan
        tfHargaSatuan.setText(df.format(hargaSatuan));

        // Tampilkan stok dan satuan ke text field
        tfStok.setText(String.valueOf(stokSisa));
        tfSatuan.setText(satuan);

        // 6. UPDATE PERHITUNGAN
        // Panggil fungsi hitung agar subtotal langsung update saat harga berubah
        hitungSubtotalSparepart();
    }//GEN-LAST:event_cbSparepartActionPerformed

